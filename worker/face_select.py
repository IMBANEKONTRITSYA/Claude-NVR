"""Сопоставление лица, найденного на полноразмерном снимке, с тем, которое
сработало на кадре аналитики.

Вынесено из worker.py отдельным модулем по той же причине, что backoff.py и
hwaccel.py: worker.py тянет cv2/insightface/sklearn, которых нет в CI-джобе
воркера (см. .github/workflows/ci.yml), и логика внутри него тестами не
покрывается. Здесь чистый stdlib, поэтому CI её проверяет.
"""


def bbox_center(bbox) -> tuple[float, float]:
    x1, y1, x2, y2 = bbox
    return (x1 + x2) / 2, (y1 + y2) / 2


def bbox_diagonal(bbox) -> float:
    x1, y1, x2, y2 = bbox
    return ((x2 - x1) ** 2 + (y2 - y1) ** 2) ** 0.5


def pick_matching_face(boxes, expected_bbox, max_center_drift: float = 1.5, taken=None):
    """Индекс лица, наиболее похожего на ожидаемое, либо None.

    `boxes` — рамки лиц, найденных на полноразмерном снимке, в координатах
    этого снимка. `expected_bbox` — та же рамка, что сработала на кадре
    аналитики, пересчитанная в координаты снимка (см. scale_bbox).

    Зачем вообще сопоставлять: снимок камера отдаёт на 100-300 мс позже
    кадра, на котором сработала детекция, и в кадре может быть несколько
    человек. Брать первое попавшееся лицо — значит иногда подписывать
    карточку персоны чужим лицом и, что хуже, класть чужой эмбеддинг в
    событие, по которому потом идёт поиск.

    `taken` — индексы лиц снимка, уже отданные другим персонам этого же
    кадра. Один снимок разбирается на все лица кадра сразу, и без этого
    множества двум разным людям мог бы достаться один и тот же кроп с
    одним и тем же эмбеддингом: ближайшим к обоим оказывается одно лицо,
    когда второго на снимке уже нет (человек успел уйти за те 100-300 мс,
    что снимок ехал). Тому, кому лицо не досталось, вызывающий код режет
    кроп из кадра аналитики — мыльный, но заведомо его собственный.

    Порог смещения — полторы диагонали ожидаемой рамки. Если ближайшее лицо
    дальше, считаем, что нужный человек ушёл из кадра: вызывающий код
    откатывается на кроп из кадра аналитики.
    """
    if not boxes:
        return None
    ecx, ecy = bbox_center(expected_bbox)
    limit = (bbox_diagonal(expected_bbox) or 1.0) * max_center_drift

    best_idx, best_dist = None, None
    for i, box in enumerate(boxes):
        if taken and i in taken:
            continue
        cx, cy = bbox_center(box)
        dist = ((cx - ecx) ** 2 + (cy - ecy) ** 2) ** 0.5
        if best_dist is None or dist < best_dist:
            best_idx, best_dist = i, dist
    if best_dist is None or best_dist > limit:
        return None
    return best_idx
