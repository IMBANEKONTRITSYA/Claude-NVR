"""Окна наблюдения слоя аналитики и отбор сегментов без движения.

SPEC §6 требует режим «запись только при движении (опционально)». Прямо
исполнить это требование нельзя: по §2 слой записи ведёт MediaMTX, он
пишет remux'ом без декодирования и о движении ничего не знает, а связать
его с аналитикой — значит нарушить главное свойство архитектуры («отказ
аналитики НЕ влияет на запись»). Останавливать и запускать запись по
сигналу аналитики означало бы ровно это: падение воркера оставило бы
объект без записи вовсе.

Поэтому режим реализован постобработкой: пишется всё, а сегмент, внутри
которого движения не было, удаляется досрочно — раньше своего retention.
Для оператора результат тот же (в архиве остаётся только движение), но
отказ аналитики приводит к худшему случаю «архив занял больше места», а
не «записи нет».

**Главная опасность этого механизма — удалить архив по незнанию.**
«Движения не было» и «мы не смотрели» на уровне БД выглядят одинаково:
в обоих случаях за период нет ни одной отметки о движении. Камера, у
которой воркер сутки не работал (упал, стоял на паузе по расписанию §6,
не успел прогрузить модель), отдала бы весь свой архив на удаление.
Поэтому отметки пишутся не о движении, а о **наблюдении**: каждое окно
говорит «в этот промежуток аналитика смотрела камеру» и отдельно — было
ли в нём движение. Сегмент удаляется, только если он **целиком** покрыт
окнами наблюдения и ни одно из них не сообщает о движении. Нет
наблюдения — сегмент остаётся, то есть отказ аналитики деградирует в
обычную непрерывную запись.

Окна пишутся пачками по минуте, а не по каждому кадру: при 5 FPS на
канал покадровые отметки дали бы 432 000 строк в сутки на камеру, тогда
как решение об удалении принимается над сегментами длиной 5–10 минут, и
минутной гранулярности для него с запасом достаточно.

Модуль намеренно чистый (только stdlib): и накопление окон, и отбор
сегментов проверяются тестами напрямую, без Postgres и без OpenCV,
поэтому идут в лёгкой CI-джобе воркера.
"""
from __future__ import annotations

from collections import defaultdict
from datetime import datetime, timedelta
from typing import NamedTuple

# Длина окна: накопив столько секунд наблюдения, трекер закрывает окно и
# отдаёт его на запись. Минута — компромисс между числом строк (1440 на
# камеру в сутки) и задержкой, с которой отметка о движении становится
# видна уборке.
MAX_WINDOW_SEC = 60.0

# Разрыв между наблюдениями, после которого окно закрывается, а покрытие
# считается прерванным. Кадры приходят не реже idle_fps (по умолчанию 2
# в секунду даже в полном покое), поэтому 15 секунд — это уже не
# «проредили частоту», а «камера отвалилась, поток переоткрывается,
# воркер перезапущен». Такой промежуток обязан остаться дырой в покрытии:
# что происходило в кадре, пока никто не смотрел, неизвестно.
MAX_GAP_SEC = 15.0

# Запас до и после движения, который сохраняется вместе с ним (pre/post
# record промышленных NVR). Человек входит в кадр не в тот момент, когда
# сработал детектор, и хвост события так же важен, как его начало.
DEFAULT_GUARD_SEC = 10.0

# Возраст, с которого сегмент вообще можно судить. Окно закрывается через
# MAX_WINDOW_SEC, запись в БД идёт следующим наблюдением, уборка ходит
# раз в несколько минут — сегмент, дописанный только что, ещё не имеет
# всех своих окон, и «покрытия нет» для него означало бы не «не
# смотрели», а «ещё не записали». Пять минут — с запасом больше суммы
# этих задержек.
SETTLE_SEC = 300.0


class Window(NamedTuple):
    """Промежуток наблюдения одной камеры и было ли в нём движение."""

    started_ts: float
    ended_ts: float
    motion: bool


class MotionWindowTracker:
    """Накопитель окон наблюдения для одной нити камеры.

    Живёт в цикле кадров: на каждый обработанный кадр вызывается
    `observe()`, и когда очередное окно готово, оно возвращается для
    записи в БД. Состояние — три поля, никаких обращений наружу: нить
    камеры не должна ходить в Postgres чаще, чем раз в минуту (цикл 23:
    обращение к БД в цикле кадров — самый вероятный источник исключений,
    уносящих нить).
    """

    def __init__(self, *, max_window_sec: float = MAX_WINDOW_SEC,
                 max_gap_sec: float = MAX_GAP_SEC) -> None:
        self.max_window_sec = max_window_sec
        self.max_gap_sec = max_gap_sec
        self._start: float | None = None
        self._last: float = 0.0
        self._motion = False

    def observe(self, ts: float, motion: bool) -> list[Window]:
        """Отметить обработанный кадр; вернуть закрывшиеся окна (0 или 1).

        Окно закрывается в двух случаях: набралась полная длина либо в
        наблюдении случился разрыв. Во втором случае окно закрывается
        **предыдущим** наблюдением, а не текущим: промежуток между ними
        никто не видел, и заносить его в покрытие нельзя.
        """
        if self._start is None:
            self._start, self._last, self._motion = ts, ts, motion
            return []

        if ts - self._last > self.max_gap_sec:
            closed = Window(self._start, self._last, self._motion)
            self._start, self._last, self._motion = ts, ts, motion
            return [closed]

        self._last = ts
        # Движение «залипает» на всё окно: одного кадра с движением
        # достаточно, чтобы минута считалась содержащей движение. Обратная
        # трактовка (большинство кадров) удалила бы сегмент, в котором
        # человек мелькнул в кадре один раз.
        self._motion = self._motion or motion

        if self._last - self._start >= self.max_window_sec:
            closed = Window(self._start, self._last, self._motion)
            # Новое окно начинается тем же кадром, а не следующим: иначе
            # между окнами оставался бы зазор в кадр, и покрытие было бы
            # рваным. Движение этого кадра попадает в оба окна — это
            # осознанная избыточность в безопасную сторону (лишняя
            # отметка о движении сохраняет сегмент, пропущенная — удаляет).
            self._start, self._last, self._motion = ts, ts, motion
            return [closed]
        return []

    def close(self) -> list[Window]:
        """Закрыть текущее окно — при остановке нити камеры.

        Без этого последние до минуты наблюдения терялись бы при каждом
        перезапуске нити, а manager() пересоздаёт её каждые ~10 с при
        проблемах с потоком: архив рабочей камеры оказался бы усеян
        дырами в покрытии ровно там, где поток и без того нестабилен.
        """
        if self._start is None:
            return []
        closed = Window(self._start, self._last, self._motion)
        self._start = None
        self._motion = False
        return [closed]


def _merge(intervals: list[tuple[datetime, datetime]],
           join: timedelta) -> list[tuple[datetime, datetime]]:
    """Слить пересекающиеся и соседние промежутки (зазор ≤ `join`)."""
    if not intervals:
        return []
    out: list[tuple[datetime, datetime]] = []
    for start, end in sorted(intervals):
        if out and start - out[-1][1] <= join:
            if end > out[-1][1]:
                out[-1] = (out[-1][0], end)
        else:
            out.append((start, end))
    return out


def _covers(merged: list[tuple[datetime, datetime]],
            start: datetime, end: datetime) -> bool:
    """Целиком ли `[start, end]` лежит в одном из слитых промежутков."""
    return any(a <= start and end <= b for a, b in merged)


def _overlaps(merged: list[tuple[datetime, datetime]],
              start: datetime, end: datetime) -> bool:
    """Пересекается ли `[start, end]` хоть с одним промежутком."""
    return any(a <= end and start <= b for a, b in merged)


def segments_without_motion(segments, windows, *,
                            guard_sec: float = DEFAULT_GUARD_SEC,
                            join_sec: float = MAX_GAP_SEC) -> list:
    """Сегменты, которые можно удалить в режиме «запись только по движению».

    `segments` — объекты с `camera_id`, `started_at`, `ended_at`;
    `windows` — объекты с теми же полями плюс `motion`. Возвращаются те же
    объекты сегментов, чтобы вызывающий сразу удалил строки.

    Два условия, и оба обязательны:

    * сегмент **целиком** покрыт окнами наблюдения этой камеры (соседние
      окна сливаются, если зазор между ними не больше `join_sec` — то
      есть меньше разрыва, при котором трекер и сам закрыл бы окно);
    * ни одно окно с движением не пересекает сегмент, расширенный на
      `guard_sec` в обе стороны.

    Частичное покрытие не считается: сегмент, у которого просмотрена
    половина, а вторая половина пришлась на перезапуск воркера, остаётся
    в архиве. Иначе достаточно было бы наблюдать одну секунду из десяти
    минут, чтобы удалить весь сегмент.
    """
    coverage: dict[int, list[tuple[datetime, datetime]]] = defaultdict(list)
    motion: dict[int, list[tuple[datetime, datetime]]] = defaultdict(list)
    for w in windows:
        coverage[w.camera_id].append((w.started_at, w.ended_at))
        if w.motion:
            motion[w.camera_id].append((w.started_at, w.ended_at))

    join = timedelta(seconds=max(0.0, join_sec))
    merged_cov = {cam: _merge(v, join) for cam, v in coverage.items()}
    # Промежутки движения сливаются только по фактическому пересечению:
    # зазор между двумя окнами с движением — это наблюдавшийся покой, и
    # растягивать движение на него незачем, запас даёт `guard_sec`.
    merged_motion = {cam: _merge(v, timedelta(0)) for cam, v in motion.items()}

    guard = timedelta(seconds=max(0.0, guard_sec))
    out = []
    for seg in segments:
        cov = merged_cov.get(seg.camera_id)
        if not cov or not _covers(cov, seg.started_at, seg.ended_at):
            continue
        if _overlaps(merged_motion.get(seg.camera_id, []),
                     seg.started_at - guard, seg.ended_at + guard):
            continue
        out.append(seg)
    return out
