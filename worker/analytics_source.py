"""Выбор потока, по которому идёт аналитика (SPEC §2, §15).

SPEC называет допустимые источники кадров для слоя аналитики поимённо и
с условием:

* §2 — «детекция по ОСНОВНОМУ потоку либо субпотоку **с разрешением не
  ниже 640×480**»;
* §15 — «Источник кадров: основной поток либо субпоток с разрешением
  ≥ 640×480».

То есть источников не два, а полтора: основной поток допустим всегда, а
субпоток — только когда дотягивает до порога. Субпоток ниже порога SPEC
источником кадров не называет вовсе, и подставлять его вместо основного
нельзя, даже если он задан у камеры.

Почему это не теоретическая оговорка. §1 описывает типичный субпоток как
«H.265, CIF-D1»: CIF — это 352×288, вчетверо меньше порога по площади.
Автообнаружение ONVIF (§3) заполняет поле субпотока **самым маленьким**
профилем камеры (`onvif_client.select_stream_profiles` берёт `ranked[0]`),
то есть штатный путь заведения камеры кладёт в это поле ровно тот поток,
который порогу не удовлетворяет. Лицо на кадре 352×288 занимает пару
десятков пикселей — детектор его либо не видит, либо отдаёт эмбеддинг, по
которому потом не работает ни узнавание, ни поиск §15.

Порог трактуется как «обе стороны не меньше названных»: ширина ≥ 640 и
высота ≥ 480. Альтернативное прочтение — «площадь не меньше 640×480
пикселей» — на форматах, которые перечисляет сам SPEC, даёт тот же ответ
(CIF 352×288 не проходит по обоим, D1 720×576 проходит по обоим), и
расходится только на широких кадрах вроде 800×450. Выбрано построчное
прочтение: оно буквальнее и строже, а решает здесь высота — лицо в кадре
вытянуто по вертикали, и именно вертикальных пикселей на нём не хватает.
Кадр 640×360, который комментарии в worker.py много лет называют типовым
потоком аналитики, не проходит порог именно по высоте.

Модуль намеренно на чистом stdlib и без cv2: worker.py тянет
cv2/insightface/sklearn, которых нет в лёгкой джобе воркера в CI, и его
внутренняя логика тестами не покрывается (та же причина, что у
face_select.py и backoff.py). Решение вынесено сюда целиком, а в worker.py
осталось только измерение разрешения у открытого захвата.
"""

MIN_ANALYTICS_WIDTH = 640
MIN_ANALYTICS_HEIGHT = 480

# Значения поля `reason` решения. Уезжают в лог и в §9-мониторинг, поэтому
# это часть наблюдаемого поведения, а не внутренняя деталь.
NO_SUB = "no_sub"                            # субпоток не задан — работаем по основному
SUB_MEETS_FLOOR = "sub_meets_floor"          # субпоток дотягивает до порога
SUB_BELOW_FLOOR = "sub_below_floor"          # субпоток ниже порога, ушли на основной
SUB_BELOW_FLOOR_NO_MAIN = "sub_below_floor_no_main"  # ниже порога, но уходить некуда
SUB_RESOLUTION_UNKNOWN = "sub_resolution_unknown"    # разрешение не измерилось


def meets_floor(width, height) -> bool:
    """Дотягивает ли кадр `width`×`height` до порога §2/§15.

    Неизвестное разрешение (None, 0, отрицательное) — не «ниже порога»:
    для этого случая есть отдельная ветка в choose_analytics_source, и
    смешивать «мы измерили и там мало» с «мы не смогли измерить» нельзя.
    Первое — повод сменить поток, второе — повод не трогать ничего.
    """
    if not width or not height or width <= 0 or height <= 0:
        return False
    return width >= MIN_ANALYTICS_WIDTH and height >= MIN_ANALYTICS_HEIGHT


def resolution_known(width, height) -> bool:
    """Удалось ли вообще измерить разрешение потока."""
    return bool(width) and bool(height) and width > 0 and height > 0


def choose_analytics_source(main_url: str, sub_url: str | None,
                            sub_width=None, sub_height=None) -> dict:
    """Каким потоком кормить детектор.

    `sub_width`/`sub_height` — фактически измеренное разрешение субпотока
    (см. worker.capture_resolution), а не то, что обещает профиль ONVIF:
    прошивки регулярно врут в GetProfiles, а §2 говорит о разрешении
    кадра, который реально приходит.

    Возвращает словарь с ключами `url`, `stream` ("sub"/"main"), `reason`,
    `width`, `height`. Словарь, а не кортеж, потому что то же содержимое
    целиком уходит в §9-мониторинг: дежурный должен видеть не только
    «аналитика по основному потоку», но и почему — то есть числа, из-за
    которых так вышло (приём цикла 52: «эта величина откуда берётся?»).

    Неизмеримое разрешение оставляет субпоток на месте. Соблазн уйти на
    основной «на всякий случай» велик и неверен: измерение не удаётся на
    сборках OpenCV без нужного свойства и на редких прошивках, то есть
    отказ измерения — свойство нашей стороны, а не камеры. Уход на
    основной поток стоит кратно дороже по CPU (см. §16: декодирование —
    самая тяжёлая часть слоя аналитики), и платить эту цену вслепую, ничего
    не зная о субпотоке, — худший из вариантов. Случай виден в мониторинге
    отдельной причиной.
    """
    if not sub_url:
        return {"url": main_url, "stream": "main", "reason": NO_SUB,
                "width": None, "height": None}

    if not resolution_known(sub_width, sub_height):
        return {"url": sub_url, "stream": "sub", "reason": SUB_RESOLUTION_UNKNOWN,
                "width": None, "height": None}

    if meets_floor(sub_width, sub_height):
        return {"url": sub_url, "stream": "sub", "reason": SUB_MEETS_FLOOR,
                "width": sub_width, "height": sub_height}

    # Субпоток ниже порога. Основной поток — единственный оставшийся
    # источник, который §2 и §15 называют допустимым.
    if main_url and main_url != sub_url:
        return {"url": main_url, "stream": "main", "reason": SUB_BELOW_FLOOR,
                "width": sub_width, "height": sub_height}

    # Уходить некуда: основного адреса нет либо он тот же самый. Работаем
    # тем, что есть, — остановить аналитику здесь было бы хуже (§2: слои
    # независимы, но аналитика всё же должна работать), — но причина
    # уезжает в мониторинг, чтобы это не осталось незамеченным.
    return {"url": sub_url, "stream": "sub", "reason": SUB_BELOW_FLOOR_NO_MAIN,
            "width": sub_width, "height": sub_height}


def describe(decision: dict) -> str:
    """Человекочитаемое пояснение для §9-мониторинга.

    Живёт рядом с решением, а не во фронтенде: формулировка и набор причин
    меняются вместе, и разъезжаться им нельзя.
    """
    reason = decision.get("reason")
    w, h = decision.get("width"), decision.get("height")
    floor = f"{MIN_ANALYTICS_WIDTH}×{MIN_ANALYTICS_HEIGHT}"
    if reason == NO_SUB:
        return "субпоток не задан — аналитика по основному потоку"
    if reason == SUB_MEETS_FLOOR:
        return f"субпоток {w}×{h} — не ниже порога {floor}"
    if reason == SUB_BELOW_FLOOR:
        return (f"субпоток {w}×{h} ниже порога {floor} — "
                f"аналитика переведена на основной поток")
    if reason == SUB_BELOW_FLOOR_NO_MAIN:
        return (f"субпоток {w}×{h} ниже порога {floor}, "
                f"основной поток недоступен — детекция ухудшена")
    if reason == SUB_RESOLUTION_UNKNOWN:
        return "разрешение субпотока не измерилось — поток оставлен без изменений"
    return ""
