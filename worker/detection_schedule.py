"""Расписание детекции (SPEC §6: «Расписание детекции (день/ночь, рабочие
часы)»).

Отдельный модуль без зависимостей от cv2/БД: это чистая функция от
(расписание, момент времени), и её нужно проверять на фиксированных датах, а
не на «сейчас» — иначе тест на ночное окно проходил бы или падал в
зависимости от времени прогона CI.

Формат расписания (JSON-колонка `cameras.detection_schedule`):

    {"enabled": true,
     "windows": [{"days": [0, 1, 2, 3, 4], "start": "08:00", "end": "18:00"}]}

`days` — 0 = понедельник, как в `datetime.weekday()` и в расписании отчётов
(§8), чтобы в системе был один способ нумеровать дни недели.

Два решения, которые определяют поведение:

**Окно через полночь.** `start` больше `end` (22:00–06:00) означает окно,
переходящее на следующие сутки, а не пустое окно. Наивная проверка
`start <= t < end` для такого окна ложна всегда — «ночная охрана» молча не
работала бы ни одной ночи, и заметили бы это не сразу: система выглядит
исправной, детекция просто не срабатывает. §6 называет режим «день/ночь»
прямо, то есть ночное окно — не экзотика, а половина сценария.

**Отсутствие расписания и `enabled: false` — это «детекция всегда».**
Не «никогда»: расписание не задано у всех существующих камер, и трактовка
«пусто = выключено» на обновлении разом остановила бы аналитику на объекте
без единого сообщения.
"""
from datetime import datetime

# Потолок на число окон. Расписание правится в браузере и уезжает в JSON-
# колонку; десяти интервалов хватает на любой разумный график (рабочие часы
# по будням + выходные + ночь), а ограничение не даёт превратить колонку в
# способ положить воркер разбором тысяч интервалов на каждом кадре.
MAX_WINDOWS = 10


def _parse_hhmm(value) -> int | None:
    """'HH:MM' -> минуты от полуночи. None — если разобрать нельзя.

    Некорректное значение не должно ронять нить камеры: расписание
    приходит из БД, а не из проверенного на входе кода, и единственная
    битая строка (ручная правка, миграция, старый формат) иначе
    останавливала бы детекцию на камере навсегда.
    """
    if not isinstance(value, str):
        return None
    parts = value.strip().split(":")
    if len(parts) != 2:
        return None
    try:
        hours, minutes = int(parts[0]), int(parts[1])
    except ValueError:
        return None
    if not (0 <= hours <= 23 and 0 <= minutes <= 59):
        return None
    return hours * 60 + minutes


def _window_active(window, weekday: int, minute_of_day: int) -> bool:
    if not isinstance(window, dict):
        return False
    start = _parse_hhmm(window.get("start"))
    end = _parse_hhmm(window.get("end"))
    if start is None or end is None:
        return False

    days = window.get("days")
    # Окно без списка дней действует каждый день — так задаётся «ночь всегда»
    # без перечисления всех семи.
    if isinstance(days, list) and days:
        pass
    else:
        days = list(range(7))

    if start == end:
        # Вырожденное окно. Трактуется как «круглые сутки», а не «нисколько»:
        # 00:00–00:00 — самая естественная запись для «весь день», и пустой
        # интервал в этом месте означал бы выключенную детекцию при
        # включённом расписании.
        return weekday in days

    if start < end:
        return weekday in days and start <= minute_of_day < end

    # Окно через полночь (22:00–06:00) разбивается на две половины.
    # День недели относится к НАЧАЛУ окна: смена, начавшаяся в пятницу
    # вечером, продолжается в субботу ночью, и выключать её в полночь
    # неверно — для дежурного это одна ночь, а не две.
    if minute_of_day >= start:          # вечерняя половина, сегодняшнее окно
        return weekday in days
    if minute_of_day < end:             # утренняя половина, вчерашнее окно
        return ((weekday - 1) % 7) in days
    # Промежуток между концом и началом (день при ночном окне) — не в окне.
    # Без этой ветки «ночная охрана» считалась бы активной круглосуточно:
    # ошибка ровно противоположная той, от которой защищает сам разбор
    # через полночь, и такая же незаметная — детекция идёт всегда, просто
    # расписание ни на что не влияет.
    return False


def schedule_active(schedule, when: datetime) -> bool:
    """Должна ли идти детекция в момент `when`.

    `when` — локальное время сервера: администратор объекта задаёт «с 8 до
    18» в своём часовом поясе, а не в UTC (тот же выбор, что и в расписании
    отчётов §8; для развёртывания это отмечено в чек-листе).
    """
    if not isinstance(schedule, dict) or not schedule.get("enabled"):
        return True

    windows = schedule.get("windows")
    if not isinstance(windows, list) or not windows:
        # Включённое расписание без единого окна — «детекция не идёт
        # никогда». Здесь это осмысленно и обратимо (снять галочку), в
        # отличие от отсутствия расписания вовсе.
        return False

    minute_of_day = when.hour * 60 + when.minute
    weekday = when.weekday()
    return any(_window_active(w, weekday, minute_of_day) for w in windows[:MAX_WINDOWS])
