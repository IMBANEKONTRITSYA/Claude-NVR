"""Наблюдаемое состояние проходов уборки архива (SPEC §5, §9).

**Зачем отдельно от самой уборки.** Цикл 57 увёл часовую уборку архива из
нити менеджера в свою (`start_cleanup_pass()` в `worker.py`) — иначе её
900-секундный бюджет означал четверть часа без статусов потоков и без
циклической перезаписи. Правка верная, но у неё есть цена, которую та же
правка и создала: **из-под сторожа живости уборка вышла, а под чей-то
надзор не встала**.

До неё зависший том выглядел так: этап `cleanup` превышает бюджет →
`/health` отдаёт 503 с именем этапа → healthcheck контейнера краснеет →
дежурный видит причину. После — так: нить сидит в `unlink()` сколько
угодно, менеджер бодро крутится, `/health` зелёный, и единственный след
события в системе — строка `«проход уборки архива идёт дольше часа»` в
stdout воркера. Раз в час. На объекте, где журнал воркера не читает никто.

А отказ уборки виден снаружи ровно как исправная работа: диск просто
заполняется. Причём заполняется он не быстро и не сразу — то есть
замечают его тогда, когда циклическая перезапись уже сносит вчерашний
архив вместо просроченного.

Поэтому состояние прохода едет в §9 — туда же, куда цикл 55 увёл
состояние загрузки модели по тому же поводу и по той же причине.

**Почему это отдельный модуль, а не пара переменных в `worker.py`.**
Ровно из тех же соображений, что `liveness.py` и `model_loader.py`: он
обязан работать в воркере рядом с cv2/insightface/onnxruntime и
одновременно проверяться лёгкой джобой CI, которая их не ставит. Тесты
самой уборки этого позволить себе не могут — они поднимают настоящий
`manager()` и потому идут через `pytest.importorskip("worker")`, то есть
**в CI молча скипаются**. Правило показа, которое решает, звать дежурного
или молчать, проверяться при этом обязано всегда.

**Что считается, а что нет.** Модуль ничего не измеряет сам и ничем не
управляет: он только помнит, что ему сообщили о проходах, и отвечает на
вопрос «в каком состоянии уборка сейчас». Решение «пора убирать»
по-прежнему принимает менеджер, а исполняет нить уборки.
"""
from __future__ import annotations

import threading
import time

# Состояния прохода, как их видит §9.
IDLE = "idle"        # ни одного прохода ещё не было
RUNNING = "running"  # проход идёт прямо сейчас
DONE = "done"        # последний проход завершился целиком
FAILED = "failed"    # последний проход завершился, но какой-то этап упал


class CleanupStatus:
    """Состояние проходов уборки архива для §9.

    Обновляется из нити уборки (`pass_started`/`pass_finished`) и из нити
    менеджера (`pass_skipped`), читается из нити менеджера при публикации
    состояния слоя записи. Поэтому всё под одним замком: снимок,
    собранный наполовину из старого прохода и наполовину из нового, врал
    бы ровно в тот момент, ради которого он и собирается.
    """

    def __init__(self, clock=time.monotonic):
        # monotonic, а не time(): перевод системных часов на объекте без
        # интернета (первая синхронизация ntp) не должен ни «омолаживать»
        # идущий проход, ни показывать его длительность отрицательной.
        # Тот же довод, что в `liveness.Heartbeat`.
        self._clock = clock
        self._lock = threading.Lock()
        self._state = IDLE
        self._since = clock()
        self._last_sec: float | None = None
        self._error: str | None = None
        self._skipped = 0

    def pass_started(self) -> None:
        with self._lock:
            self._state = RUNNING
            self._since = self._clock()

    def pass_finished(self, failed=()) -> None:
        """Проход кончился. `failed` — имена упавших этапов, если были."""
        failed = list(failed)
        with self._lock:
            started = self._since
            self._last_sec = self._clock() - started
            self._error = ", ".join(failed) if failed else None
            self._state = FAILED if failed else DONE
            self._since = self._clock()

    def pass_skipped(self) -> int:
        """Запрошенный проход не стартовал — предыдущий ещё идёт.

        Возвращает счётчик пропусков. Это не диагностика «на всякий
        случай», а главный ранний признак: проход, не уложившийся в свой
        час, означает, что архив чистится медленнее, чем растёт. Диск при
        этом ещё не переполнен, и время на реакцию есть — но только если
        кто-то об этом знает.
        """
        with self._lock:
            self._skipped += 1
            return self._skipped

    def snapshot(self) -> dict:
        """Состояние для §9: идёт ли проход, сколько уже, чем кончился прошлый."""
        with self._lock:
            return {
                "state": self._state,
                "seconds": round(self._clock() - self._since, 1),
                "last_pass_sec": (round(self._last_sec, 1)
                                  if self._last_sec is not None else None),
                "error": self._error,
                "skipped": self._skipped,
            }
