/**
 * Состояние циклической перезаписи на странице §9-мониторинга.
 *
 * Пара к archiveCleanup.ts и заведена по тому же поводу: с этого цикла
 * `enforce_disk_quota()` идёт в своей нити воркера (`start_quota_pass()` в
 * worker.py, SPEC §2), а сторож живости её намеренно не сторожит — его
 * реакция на превышение бюджета — убийство процесса, и перезапуск воркера
 * из-за медленного тома остановил бы заодно слой записи. Плата та же:
 * проход стал невидимым снаружи, и его состояние надо показать.
 *
 * **Почему отдельный модуль, а не поле в cleanupBanner.** Правило показа у
 * двух проходов разное, и разница не косметическая:
 *
 * | Признак | Уборка по retention | Циклическая перезапись |
 * |---|---|---|
 * | Интервал запроса | раз в час | **каждый проход менеджера (~10 с)** |
 * | Пропуск прохода | архив чистится медленнее, чем растёт — тревога | штатный режим: любой проход длиннее 10 с даёт пропуск на следующем |
 * | Отказ | retention не отработал | **запись встанет, когда место кончится** |
 *
 * Пропуск — главный ранний признак у уборки и шум у перезаписи. Свести их
 * к одному правилу значило бы либо сыпать тревогой на каждом переполненном
 * томе, либо потерять единственный ранний признак у уборки.
 *
 * Отсюда правило показа: **молчать, пока перезапись работает**. Показываются
 * два случая:
 *
 * 1. **проход упал** — авария: перезапись и есть то, что не даёт записи
 *    встать на переполненном томе, и её отказ виден снаружи только как
 *    убывающее место;
 * 2. **проход идёт дольше обычного** — нейтральная строка: не авария, но
 *    отвечает на вопрос дежурного, который смотрит на заполненный диск, —
 *    «перезапись сломалась или просто не успевает?».
 *
 * Отказ перезаписи, в отличие от отказа уборки, замечен будет и без этой
 * страницы: `check_disk_alerts()` остаётся в нити менеджера и шлёт алерт по
 * заполнению диска в Telegram и на почту (§9). Баннер здесь не заменяет тот
 * алерт, а называет причину — алерт сообщает, что места нет, и не сообщает,
 * почему его не освобождают.
 */

import { humanDuration } from "./modelLoad";
import type { Cleanup } from "./archiveCleanup";
import { SLOW_PASS_SEC } from "./archiveCleanup";

export type Quota = Cleanup;

export type QuotaBanner = {
  tone: "warn" | "info";
  title: string;
  detail: string | null;
};

/**
 * Порог «идёт дольше обычного» — тот же, что у уборки, и по той же причине:
 * это ровно тот бюджет, что стоял у этапа `disk_quota` у сторожа живости до
 * этого цикла. До этой границы проход имел право идти, не считаясь
 * зависшим, а после неё система поднимала тревогу сама. Возвращать надо ту
 * чувствительность, которая была, а не более грубую.
 *
 * Реэкспортируется из archiveCleanup.ts, а не задаётся вторым числом:
 * совпадение здесь не случайно (обе строки в таблице бюджетов стояли с
 * одним значением 900), и два независимых литерала разъехались бы при
 * первой же правке одного из них.
 */
export { SLOW_PASS_SEC };

/** Баннер состояния циклической перезаписи, либо null — показывать нечего. */
export function quotaBanner(q: Quota | null | undefined): QuotaBanner | null {
  if (!q) return null;

  if (q.state === "failed") {
    return {
      tone: "warn",
      title: "Циклическая перезапись завершилась с ошибкой — "
        + "место на переполненном диске не освобождается.",
      detail: q.error
        ? `Упавшие проходы: ${q.error}. Это последний механизм, который не `
          + "даёт записи встать при заполнении диска (SPEC §5): пока он не "
          + "работает, запись прекратится, как только место кончится. "
          + "Подробности — в журнале воркера."
        : "Это последний механизм, который не даёт записи встать при "
          + "заполнении диска (SPEC §5): пока он не работает, запись "
          + "прекратится, как только место кончится. Подробности — в "
          + "журнале воркера.",
    };
  }

  // Пропуски (`skipped`) намеренно не показываются: проход запрашивается
  // каждые ~10 с, и любой, кто идёт дольше одного прохода менеджера, даёт
  // пропуск на следующем. На переполненном томе это установившийся режим, а
  // не сбой, и тревога по нему не гасла бы никогда — то есть перестала бы
  // что-либо значить. За длительность отвечает случай ниже.

  if (q.state === "running"
      && typeof q.seconds === "number" && q.seconds > SLOW_PASS_SEC) {
    return {
      tone: "info",
      title: `Циклическая перезапись идёт ${humanDuration(q.seconds)} — `
        + "дольше обычного.",
      detail: "Запись, статусы потоков и уборка архива при этом работают "
        + "(SPEC §2): перезапись идёт в своей нити. Освобождение места "
        + "отстаёт, пока проход не закончится — стоит проверить скорость "
        + "диска архива.",
    };
  }

  return null;
}
