/**
 * Покадровый просмотр в плеере архива (SPEC §5).
 *
 * §5 требует «встроенный плеер с покадровым просмотром». Плеер был
 * `<video controls>` — то есть ровно тем, что даёт браузер: play/pause и
 * перемотка мышью. Дознание по записи так не ведут: чтобы разобрать
 * момент прохода человека через кадр, нужно двигаться **по одному кадру**
 * в обе стороны, а не ловить нужное место ползунком.
 *
 * **Длительность кадра не берётся из константы.** У камер §1 основной
 * поток идёт 15–30 fps, и это настройка **камеры**, а не системы; в
 * `video_segments` частоты нет вовсе. Шаг в 1/25 с, взятый «типичным»,
 * на 15-кадровой камере перепрыгивал бы кадр через раз, а на 30-кадровой
 * топтался бы на месте — и то и другое выглядит как «кнопка иногда не
 * работает». Поэтому длительность кадра **измеряется по самому потоку**
 * через `requestVideoFrameCallback`, а константа ниже — только запасной
 * вариант для браузеров без него.
 *
 * Модуль чистый (без DOM) ради того же, ради чего вынесен `liveLayout`:
 * арифметику шага можно проверить тестом, а не глазами по видео.
 */

/** Запасная длительность кадра, с. Соответствует нижней границе §1
 *  (15 fps): промах в сторону **большего** шага безопаснее — оператор
 *  увидит соседний кадр, а не тот же самый, и не решит, что кнопка мертва. */
export const FALLBACK_FRAME_DURATION = 1 / 15;

/** Границы правдоподобной длительности кадра, с.
 *
 *  `requestVideoFrameCallback` отдаёт время презентации, и на первом
 *  кадре после seek разница с предыдущим — это длина скачка, а не кадра.
 *  Без этих границ один такой замер зафиксировал бы «кадр длиной 4
 *  секунды», и покадровый просмотр превратился бы в перемотку. */
export const MIN_FRAME_DURATION = 1 / 120;
export const MAX_FRAME_DURATION = 1 / 5;

/** Скорости воспроизведения (SPEC §5, разбор записи). */
export const PLAYBACK_RATES = [0.25, 0.5, 1, 2, 4] as const;
export type PlaybackRate = (typeof PLAYBACK_RATES)[number];

export const DEFAULT_RATE: PlaybackRate = 1;

/**
 * Оценка длительности кадра по разнице времён презентации двух кадров.
 *
 * `null` — «замер непригоден, оставить прежнюю оценку». Отбрасываются
 * скачки после перемотки, нули (два колбэка на один кадр) и обратный ход
 * времени.
 */
export function frameDurationFrom(delta: number): number | null {
  if (!Number.isFinite(delta) || delta <= 0) return null;
  if (delta < MIN_FRAME_DURATION || delta > MAX_FRAME_DURATION) return null;
  return delta;
}

/**
 * Время следующего/предыдущего кадра.
 *
 * `anchor` — время презентации кадра, который сейчас на экране
 * (`mediaTime` из `requestVideoFrameCallback`), то есть **точная граница
 * начала этого кадра**. `dir` — +1 вперёд, −1 назад.
 *
 * **Отсчёт идёт от якоря, а не от сетки кадров от начала файла.**
 * Первая версия строила абсолютную сетку (`floor(t / frameDur)`), и на
 * реальном видео в Chromium шаг вперёд срабатывал 4 раза из 10.
 * Причина: длительность кадра **измерена**, а не известна точно —
 * замер даёт 0.0670 с там, где на самом деле 0.06667 с. Ошибка в полпроцента
 * копится вдоль всей сетки, и её хватает, чтобы цель попала в тот же
 * кадр или перепрыгнула следующий. Якорь же — точная граница, известная
 * от самого декодера, и каждый шаг переустанавливает её заново, поэтому
 * ошибка не накапливается вовсе.
 *
 * Цель — **середина** соседнего кадра, а не его граница: браузер при
 * перемотке показывает кадр не позже запрошенного времени, и попадание
 * ровно в границу зависело бы от погрешности замера.
 *
 * Результат зажат в [0, duration]: выход за конец сбрасывал бы `<video>`
 * в состояние ended, а отрицательное время браузер молча игнорирует —
 * кнопка «назад» на первом кадре выглядела бы сломанной.
 */
export function stepTime(
  anchor: number,
  frameDuration: number,
  duration: number,
  dir: 1 | -1,
): number {
  const frame = frameDuration > 0 ? frameDuration : FALLBACK_FRAME_DURATION;
  const safeAnchor = Number.isFinite(anchor) && anchor > 0 ? anchor : 0;
  // Вперёд: следующий кадр занимает [a+f, a+2f) — целимся в a+1.5f.
  // Назад:  предыдущий занимает [a−f, a)     — целимся в a−0.5f.
  const target = safeAnchor + (dir === 1 ? 1.5 : -0.5) * frame;
  const max = Number.isFinite(duration) && duration > 0 ? duration : Infinity;
  return Math.min(Math.max(target, 0), max);
}

/**
 * Приблизительный номер кадра от начала сегмента — только для подписи.
 *
 * **Оценка, а не точное значение**, и в шаге не участвует (см. stepTime):
 * длительность кадра измерена по потоку с погрешностью порядка
 * полпроцента, и вдоль пятиминутного сегмента это уводит номер на
 * десятки кадров. Точный номер потребовал бы частоты кадров в
 * `video_segments`, которой там нет: у камер §1 это настройка камеры.
 * Для своей задачи — «видно, что позиция сдвинулась ровно на один» —
 * оценки достаточно, потому что соседние вызовы сделаны по одному якорю.
 *
 * Округление **вниз**, а не к ближайшему: в момент `t` на экране кадр,
 * начавшийся не позже `t`.
 *
 * Эпсилон — не косметика. Длительность кадра почти всегда периодическая
 * дробь (1/15, 1/30), и ровные границы попадают под неё с недолётом:
 * `10 / (1/15)` даёт 149.99999999999997, то есть на границе кадра 150
 * функция без эпсилона возвращала бы 149.
 */
export function frameNumber(current: number, frameDuration: number): number {
  const frame = frameDuration > 0 ? frameDuration : FALLBACK_FRAME_DURATION;
  const safe = Number.isFinite(current) && current > 0 ? current : 0;
  return Math.max(0, Math.floor(safe / frame + 1e-9));
}

/** Подпись позиции: «12.480 с · кадр 187». */
export function positionLabel(current: number, frameDuration: number): string {
  const safe = Number.isFinite(current) && current > 0 ? current : 0;
  return `${safe.toFixed(3)} с · кадр ${frameNumber(safe, frameDuration)}`;
}

export function isPlaybackRate(v: unknown): v is PlaybackRate {
  return (PLAYBACK_RATES as readonly number[]).includes(v as number);
}
