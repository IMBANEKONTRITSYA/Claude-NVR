/**
 * Представление FPS и битрейта потоков записи (SPEC §9).
 *
 * §9 перечисляет содержимое статуса потоков поимённо — «онлайн/оффлайн,
 * FPS, битрейт», — и до этого модуля «Мониторинг» показывал из трёх
 * величин одну. Вместо битрейта стоял столбец «Принято, МБ»:
 * накопительный счётчик, по которому камера, отдающая 200 кбит/с вместо
 * четырёх мегабит, неотличима от исправной — её число просто растёт
 * медленнее, а скорость роста глазами никто не измеряет.
 *
 * Логика вынесена из `pages/Monitoring.tsx` в отдельный модуль по тем же
 * соображениям, что и `liveLayout.ts`: правила «чего не показывать» —
 * решения, а не разметка, и проверяются они тестом, а не глазами.
 */

/** Величина не измерена. Это НЕ ноль: прочерк и «0 кбит/с» — разные ответы. */
export const NO_VALUE = "—";

/**
 * Битрейт человеку: кбит/с до мегабита, дальше Мбит/с с одним знаком.
 *
 * `null` — «ещё не измерен» (первая проба счётчика, потерянная связь с
 * медиасервером) и рисуется прочерком. Ноль рисуется нулём: путь заведён,
 * байты не идут — это ответ, а не отсутствие ответа, и именно его надо
 * увидеть на камере, которая числится онлайн.
 */
export function formatBitrate(kbps: number | null | undefined): string {
  if (kbps === null || kbps === undefined || !Number.isFinite(kbps)) return NO_VALUE;
  if (kbps < 1000) return `${Math.round(kbps)} кбит/с`;
  return `${(kbps / 1000).toFixed(1)} Мбит/с`;
}

/** Суммарный входящий поток объекта (SPEC §16: «сумма битрейтов всех камер»). */
export function formatTotalBitrate(kbps: number | null | undefined): string {
  return formatBitrate(kbps);
}

/**
 * FPS человеку: целое, если целое, иначе один знак.
 *
 * Дробная часть тут не педантизм: камера, просевшая с 25 до 24.2, — это
 * потери в сети, и округление до «24» их прячет.
 */
export function formatFps(fps: number | null | undefined): string {
  if (fps === null || fps === undefined || !Number.isFinite(fps)) return NO_VALUE;
  return Number.isInteger(fps) ? String(fps) : fps.toFixed(1);
}

/**
 * Поток числится живым, а байты не идут.
 *
 * Ровно то состояние, которое §9 просит заметить: путь заведён и
 * `available`, то есть по статусу камера «онлайн», но данных с неё нет.
 * До появления битрейта это состояние в интерфейсе не отображалось вовсе
 * — накопительный счётчик у такой камеры остаётся ненулевым.
 */
export function isSilentStream(status: string, kbps: number | null | undefined): boolean {
  return status === "online" && kbps === 0;
}
