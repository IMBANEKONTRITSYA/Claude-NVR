/**
 * Состояние часовой уборки архива на странице §9-мониторинга.
 *
 * До цикла 57 уборка шла в нити менеджера воркера, и её сторожил
 * общий сторож живости: проход дольше 900 секунд считался зависанием, а
 * зависание менеджера видно снаружи само — контейнер краснеет, `/health`
 * отдаёт 503. Показывать состояние уборки отдельно было незачем.
 *
 * С переносом уборки в свою нить (`start_cleanup_pass()` в worker.py,
 * SPEC §2) сторож её намеренно не сторожит: его реакция — убийство
 * процесса, а убить процесс из-за медленного `unlink()` по HDD значило бы
 * перезапустить вместе с уборкой слой записи. Плата за это — уборка стала
 * невидимой: единственным следом события остаётся строка в stdout
 * воркера, а диск, который перестал чиститься, снаружи выглядит просто
 * заполняющимся. Дежурный узнаёт о причине последним.
 *
 * Отсюда правило показа: **молчать, пока уборка работает нормально**.
 * Часовой проход, который идёт свои полминуты и завершается, — не новость,
 * и баннер на каждый час приучил бы его пролистывать. Показываются ровно
 * три случая, в которых от дежурного что-то зависит:
 *
 * 1. **проход упал** — retention не отработал, архив не чистится;
 * 2. **проходы пропускаются** — предыдущий не успевает за час, то есть
 *    архив чистится медленнее, чем растёт (это и есть будущий
 *    переполненный диск, только видимый заранее);
 * 3. **проход идёт дольше обычного** — нейтральная строка со временем:
 *    не авария, но объясняет, почему место пока не освобождается.
 *
 * Вынесено отдельным модулем, чтобы решение проверялось юнит-тестами без
 * рендера страницы (тот же приём, что в modelLoad.ts).
 */

import { humanDuration } from "./modelLoad";

export type CleanupState = "idle" | "running" | "done" | "failed";

export type Cleanup = {
  state?: CleanupState | null;
  seconds?: number | null;
  last_pass_sec?: number | null;
  error?: string | null;
  skipped?: number | null;
};

export type CleanupBanner = {
  tone: "warn" | "info";
  title: string;
  detail: string | null;
};

/**
 * Ровно тот бюджет, что стоял у этапа `cleanup` у сторожа живости до
 * цикла 57: до этой границы проход имел право идти, не считаясь зависшим,
 * а после неё система поднимала тревогу сама.
 *
 * Порог взят именно оттуда, а не с потолка и не от часа, на котором
 * воркер отказывается стартовать следующий проход: час — это когда
 * уборка уже провалила свой интервал, а 900 секунд — когда о ней ещё
 * только стоит забеспокоиться. Возвращать надо ту чувствительность,
 * которая была, а не более грубую.
 */
export const SLOW_PASS_SEC = 900;

/** Баннер состояния уборки архива, либо null — показывать нечего. */
export function cleanupBanner(c: Cleanup | null | undefined): CleanupBanner | null {
  if (!c) return null;

  // Упавший проход — первым: если уборка и падает, и не укладывается в час,
  // чинить надо отказ, а не темп.
  if (c.state === "failed") {
    return {
      tone: "warn",
      title: "Уборка архива завершилась с ошибкой — retention не отработал.",
      detail: c.error
        ? `Упавшие проходы: ${c.error}. Подробности — в журнале воркера.`
        : "Подробности — в журнале воркера.",
    };
  }

  const skipped = typeof c.skipped === "number" ? c.skipped : 0;
  if (skipped > 0) {
    return {
      tone: "warn",
      title: "Уборка архива не укладывается в свой час — "
        + `пропущено проходов: ${skipped}.`,
      detail: "Архив чистится медленнее, чем растёт: место продолжит "
        + "убывать, пока не сработает циклическая перезапись (SPEC §5). "
        + "Стоит проверить скорость диска архива и глубину хранения.",
    };
  }

  if (c.state === "running"
      && typeof c.seconds === "number" && c.seconds > SLOW_PASS_SEC) {
    return {
      tone: "info",
      title: `Уборка архива идёт ${humanDuration(c.seconds)} — дольше обычного.`,
      detail: "Запись, статусы потоков и циклическая перезапись при этом "
        + "работают (SPEC §2): уборка идёт в своей нити. Освобождение "
        + "места отстаёт, пока проход не закончится.",
    };
  }

  return null;
}
