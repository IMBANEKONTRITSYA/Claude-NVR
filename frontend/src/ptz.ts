/**
 * Удержание кнопки на пульте PTZ (SPEC §4).
 *
 * Логика вынесена из компонента, потому что опасное свойство здесь ровно
 * одно и проверить его в разметке нельзя: **любое удержание должно
 * заканчиваться командой «стоп»**. Если она не уходит — купол продолжает
 * поворот, точка остаётся без обзора, и заметят это не сразу. Способов не
 * отправить её больше, чем кажется: пользователь увёл курсор с кнопки и
 * отпустил его за пределами окна, перешёл на другую страницу прямо во время
 * поворота, вкладка ушла в фон, запрос упал сетевой ошибкой.
 *
 * Вторая половина защиты — на стороне камеры: ONVIF-команда движения
 * посылается с таймаутом (onvif_client.PTZ_MOVE_TIMEOUT_SEC), поэтому
 * камера останавливается сама, даже когда остановить её некому. Здесь —
 * первая половина: сделать так, чтобы до таймаута доходило только при
 * настоящем обрыве, а не при обычном отпускании кнопки.
 */

export type PtzVector = { pan?: number; tilt?: number; zoom?: number };

/** Период повторной отправки, пока кнопка нажата.
 *
 * Заметно короче таймаута движения на стороне камеры (2 с): пока кнопку
 * держат, каждая следующая команда продлевает поворот, и он идёт непрерывно.
 * Сделать период равным таймауту нельзя — движение дёргалось бы на границе. */
export const PTZ_REPEAT_MS = 500;

export type PtzHoldOptions = {
  move: (v: PtzVector) => Promise<unknown>;
  stop: () => Promise<unknown>;
  repeatMs?: number;
  onError?: (e: unknown) => void;
};

export class PtzHold {
  private opts: PtzHoldOptions;
  private timer: ReturnType<typeof setInterval> | null = null;
  private vector: PtzVector | null = null;
  private inFlight = 0;

  constructor(opts: PtzHoldOptions) {
    this.opts = opts;
  }

  /** Нажата стрелка или кнопка зума. */
  start(v: PtzVector) {
    // Нажатие второй кнопки, не отпустив первую (мышь + клавиатура, два
    // пальца на сенсорном экране): без этого два интервала слали бы
    // противоположные направления вперемешку и камера дёргалась бы на месте.
    //
    // Смена направления идёт БЕЗ «стопа»: по спецификации следующий
    // ContinuousMove замещает текущую скорость, а посланный перед ним «стоп»
    // мог бы прийти к камере уже после нового движения (два запроса,
    // независимые соединения) и погасить его — поворот прекращался бы при
    // зажатой кнопке. Останавливает только end().
    this.cancelRepeat();
    this.vector = v;
    // force: нажатие пользователя уходит всегда, даже если предыдущая
    // команда ещё в полёте. Без этого смена направления при медленной
    // камере просто терялась — новая стрелка отрабатывала только со
    // следующего тика, то есть спустя полсекунды после нажатия.
    this.send(true);
    this.timer = setInterval(() => this.send(), this.opts.repeatMs ?? PTZ_REPEAT_MS);
  }

  /** Кнопка отпущена — или отпускание не долетело, и его подменил уход
   * курсора/потеря фокуса/размонтирование компонента. Вызывается сколько
   * угодно раз: лишний «стоп» безвреден, пропущенный — нет. */
  end() {
    const wasHolding = this.vector !== null;
    this.cancelRepeat();
    if (!wasHolding) return;   // не было удержания — нечего останавливать
    void this.runStop();
  }

  private cancelRepeat() {
    if (this.timer !== null) {
      clearInterval(this.timer);
      this.timer = null;
    }
    this.vector = null;
  }

  /** Размонтирование: остановить камеру, даже если пользователь ушёл со
   * страницы, не отпустив кнопку. */
  dispose() {
    this.end();
  }

  get holding(): boolean {
    return this.vector !== null;
  }

  private send(force = false) {
    const v = this.vector;
    if (!v) return;
    // Команда предыдущего тика ещё не вернулась: на медленной камере
    // очередь повторов росла бы быстрее, чем разбирается, и «стоп» встал бы
    // в её конец — то есть пришёл бы к камере через секунды после того, как
    // кнопку отпустили. Ограничение касается только автоповтора: нажатия
    // пользователя редки и заведомо не образуют очередь.
    if (this.inFlight && !force) return;
    this.inFlight += 1;
    this.opts.move(v)
      .catch(e => {
        this.opts.onError?.(e);
        // Ошибка движения прекращает удержание: продолжать долбить камеру,
        // которая не отвечает, незачем, а «стоп» отправить нужно — команда
        // могла дойти до камеры и не вернуть ответ.
        this.end();
      })
      .finally(() => { this.inFlight -= 1; });
  }

  private runStop() {
    return this.opts.stop().catch(e => this.opts.onError?.(e));
  }
}
