"""Сторож изоляции: после всего прогона в БД не должно остаться учёток,
заведённых тестами.

Имя файла начинается с `zz_` намеренно — pytest собирает файлы в
алфавитном порядке, и эта проверка должна идти последней, уже после всех
`test_integration_*`.

Зачем сторож, если тесты и так убирают за собой: пробел «изоляция тестов
бэкенда» жил в carryover два цикла (19-20) именно потому, что в CI он не
виден — каждый прогон получает свежий сервис-контейнер Postgres, и
протёкшая учётка никому не мешает. Ломается только повторный локальный
прогон по той же БД, причём падает не тот тест, который протёк, а
следующий, который попробует завести пользователя с тем же именем и
получит 400. Замерено в цикле 21 до исправления: 8 падений в
`test_integration_*` на полностью здоровом дереве.

Проверка ниже переводит этот отложенный эффект в немедленный: тест,
который заведёт пользователя и не уберёт его, уронит прогон сразу и
здесь, а не через один прогон и в другом файле.
"""


def test_suite_leaves_no_test_users_behind(client, admin_headers):
    """В таблице пользователей остаётся только сид `admin` (main.py:lifespan).

    Если проверка упала — какой-то тест завёл учётку и не удалил её.
    Заводить пользователей следует общей фикстурой `make_user` из
    `conftest.py`: она удаляет их в финализаторе.
    """
    r = client.get("/api/users", headers=admin_headers)
    assert r.status_code == 200, r.text
    leftovers = sorted(u["username"] for u in r.json() if u["username"] != "admin")
    assert leftovers == [], (
        f"после прогона в БД остались учётки, заведённые тестами: {leftovers}. "
        "Повторный прогон по той же БД упадёт на POST /api/users → 400 "
        "«пользователь уже существует», причём в другом тесте. "
        "Используйте фикстуру make_user из conftest.py — она убирает за собой."
    )
