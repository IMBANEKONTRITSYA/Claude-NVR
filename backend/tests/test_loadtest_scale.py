"""Нагрузочный сценарий держит масштаб большого объекта (SPEC §1, §20).

**Что здесь стережётся и что нет.** Действующая редакция ТЗ числа камер не
задаёт и прямо запрещает его хардкодить (§22): §1 объявляет 12–250+, §20
относит объект такого размера к классу «Большой (128-256+ камер)», §17
использует 120 как пример раскладки по NUMA-нодам. Поэтому 120 и 2 — это
**умолчания сценария**, а не норматив, и меняются переменными окружения.

Тесты ниже стерегут не «ТЗ требует 120», а другое: чтобы сценарий не
съехал обратно к масштабу удалённой редакции (16 камер, все в аналитике) —
на нём нагружается совсем другая система. До цикла 27 `locustfile.py`
именно это и делал: `TARGET_CAMERAS = 16`, все камеры без указания режима,
со ссылкой на «SPEC.md §14», которым в действующей редакции называется
другой раздел.

Цикл 40: сами ссылки в комментариях (`§16 требует… §26 задаёт масштаб
буквально: 120 камер») тоже оказались из удалённой редакции — в
действующей §16 это «Планирование ресурсов», §26 — «Стратегия
развёртывания», и чисел камер там нет. Числа сценария не изменились,
обоснование приведено к действующей нумерации.

Тест читает исходник, а не импортирует модуль: `locust` не входит в
зависимости бэкенда и в CI-джобе backend его нет.
"""
import re
from pathlib import Path

LOADTEST = Path(__file__).resolve().parents[2] / "loadtest"
LOCUSTFILE = LOADTEST / "locustfile.py"


def _const(name: str) -> int:
    """Значение по умолчанию у `NAME = int(os.environ.get(..., "N"))`."""
    src = LOCUSTFILE.read_text(encoding="utf-8")
    m = re.search(rf'^{name}\s*=\s*int\(os\.environ\.get\([^,]+,\s*"(\d+)"\)\)',
                  src, re.MULTILINE)
    assert m, f"в locustfile.py не найдена константа {name}"
    return int(m.group(1))


def test_scenario_covers_all_120_recording_cameras():
    """Умолчание сценария — объект класса «Большой» по §20, а не 16 камер."""
    assert _const("TARGET_CAMERAS") == 120, (
        "Умолчание нагрузочного сценария съехало со 120 камер. Само число ТЗ "
        "не предписывает (§22 запрещает его хардкодить), но 16 — это масштаб "
        "удалённой редакции, на котором нагружается другая система."
    )


def test_scenario_keeps_analytics_cameras_at_spec_default():
    """SPEC §2: аналитика — только для выбранных камер, а не для всех."""
    assert _const("ANALYTICS_CAMERAS") == 2, (
        "Число камер analytics в сценарии съехало с двух. По §16 их число "
        "упирается в ресурсы сервера, и сценарий, где в аналитике весь парк, "
        "нагружает не ту систему: §20 рекомендует GPU уже от 10-20 камер "
        "analytics, а целевое развёртывание идёт без него."
    )


def test_scenario_assigns_camera_modes():
    """Камеры должны заводиться с явным режимом, а не «как получится».

    Без `mode` в payload все 120 камер уезжают в `record_only` (режим по
    умолчанию §2), и сценарий не задевает ни одного запроса, специфичного
    для аналитики.
    """
    src = LOCUSTFILE.read_text(encoding="utf-8")
    assert '"mode": mode' in src, (
        "камеры в сценарии создаются без указания режима — тогда камер "
        "analytics не появится вовсе (§2: record_only по умолчанию)"
    )
    assert '"analytics"' in src and '"record_only"' in src


def test_grid_page_matches_spec_limit():
    """SPEC §4: грид 1/4/9/16; §3 — пагинация для объектов 100+ камер.

    Оператор опрашивает снепшоты своей страницы, а не всех 120 подряд —
    иначе нагрузка размазывается по всему парку ровным слоем, чего в
    интерфейсе не происходит.
    """
    src = LOCUSTFILE.read_text(encoding="utf-8")
    m = re.search(r"^GRID_PAGE_SIZE\s*=\s*(\d+)", src, re.MULTILINE)
    assert m, "в сценарии нет GRID_PAGE_SIZE"
    assert int(m.group(1)) == 16, "SPEC §4 ограничивает грид 16 камерами на экран"


def test_scale_is_documented_as_a_default_not_as_a_requirement():
    """Масштаб обязан быть объяснён действующим ТЗ и объявлен настраиваемым.

    Этот тест сам был носителем расхождения. До цикла 40 он требовал
    обратного — чтобы файлы ссылались на «§16 … масштаб §26», — то есть
    стерёг цитату **удалённой** редакции: в действующей §16 это
    «Планирование ресурсов», §26 — «Стратегия развёртывания», и чисел
    камер в них нет. Зелёный тест при этом означал ровно то, что ссылка
    неверна.

    Формулировка позитивная, как и прежде: упоминание старой ссылки в
    историческом абзаце («раньше здесь стояла ссылка на …») полезно, и
    запрещать строку «§26» где угодно нечего. Проверяется, что рядом с
    числом стоит действующее обоснование (§20 — класс объекта) и способ
    его изменить — иначе умолчание снова начнёт читаться как норматив,
    хотя §22 хардкод числа камер запрещает.
    """
    for path in (LOCUSTFILE, LOADTEST / "README.md"):
        text = path.read_text(encoding="utf-8")
        assert "§20" in text, (
            f"{path.name} не называет класс объекта из §20, откуда взят "
            "масштаб сценария"
        )
        assert "§22" in text, (
            f"{path.name} не оговаривает §22 — запрет хардкодить число "
            "камер; без этого умолчание читается как требование ТЗ"
        )
        assert "LOCUST_FW_CAMERAS" in text, (
            f"{path.name} не называет переменную, которой масштаб меняется "
            "под объект"
        )


def test_scenario_is_not_described_as_sixteen_cameras():
    """«Сценарий на 16 камер» — формулировка удалённой редакции ТЗ.

    Ищется именно описание сценария, а не число 16 вообще: 16 остаётся
    легитимным как размер грида (§4) и как число виртуальных операторов.
    """
    for path in (LOCUSTFILE, LOADTEST / "README.md"):
        text = path.read_text(encoding="utf-8")
        for phrase in ("сценарий на 16 камер", "сценария на 16 камер",
                       "работе с 16 камерами", "сетки на 16"):
            assert phrase not in text, (
                f"{path.name} описывает сценарий как «{phrase}» — масштаб "
                "удалённой редакции; умолчание сценария — 120 камер записи "
                "и 2 аналитики (§20 «Большой объект»)"
            )


def test_scenario_touches_recording_layer_endpoints():
    """Слой записи — главное, что масштабируется до 120 (§9, §5).

    `/api/system/record-layer` считает два агрегата по `video_segments` за
    сутки (на 120 камерах это ~34 560 строк) и потому обязан быть в
    сценарии: именно его стоимость растёт вместе с парком камер.
    """
    src = LOCUSTFILE.read_text(encoding="utf-8")
    for endpoint in ("/api/system/record-layer", "/api/system/storage"):
        assert endpoint in src, (
            f"сценарий не нагружает {endpoint} — запрос, стоимость которого "
            "растёт с числом камер и объёмом архива"
        )
