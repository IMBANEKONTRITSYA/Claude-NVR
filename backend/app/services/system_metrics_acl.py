"""Что из системного мониторинга видит оператор (SPEC §18, §9).

**Строка матрицы, у которой не было реализации.** §18 задаёт по ролям две
разные строки, и это не описка:

| Действие | Админ | Оператор | Наблюдатель |
|---|---|---|---|
| Дашборд и мониторинг | Да | **Да** | Нет |
| Системный мониторинг | Да | **Ограниченно** | Нет |

`GET /api/system/metrics` отдавал оператору **всё**, а его докстринг при
этом утверждал: «Оператору доступно ограниченно (см. матрицу прав)». То
есть ограничение было записано в трёх местах — в ТЗ, в матрице и в
собственном докстринге эндпоинта — и не существовало ни в одном.

**Где взята граница.** Не придумана: §9 перечисляет, из чего состоит
системный мониторинг, дословно — «Системный мониторинг: **CPU/RAM,
температура, место на диске**». Всё прочее в ответе (камеры, события,
сегменты, FPS, поток аналитики, состояние Redis и очереди апскейла)
относится к строке «Дашборд и мониторинг», где у оператора стоит «Да», и
трогать его нельзя.

**Почему «Ограниченно», а не «Нет».** Из четырёх величин §9 три —
телеметрия железа сервера: оператор по ним ничего не делает и делать не
вправе (смена профиля производительности, retention и бэкапов — строки со
«Нет»). Четвёртая, **место на диске**, — его собственная работа: §5
требует «индикация заполнения диска, прогноз на сколько дней хватит
места», а §18 запрещает оператору не видеть хранилище, а **настраивать**
его («Настройка retention и хранения» — Нет). Дежурный, который не видит,
что архив кончается, не может даже позвать администратора.

Отсюда: у оператора убираются CPU, RAM и температура; место на диске
остаётся.

**Чего здесь намеренно НЕ делается.** `redis_ok` и `upscale_queue` в
перечислении §9 не названы, поэтому под «Системный мониторинг» не
подводятся и оператору остаются. Убрать их значило бы ввести ограничение,
которого в ТЗ нет, — ровно та ошибка, от которой предостерегает приём
«отличать „строка ТЗ разрешает“ от „строки ТЗ нет“» (цикл 51).

Модуль на голой стандартной библиотеке и вынесен из роутера по тому же
поводу, что `face_feed_acl.py` (цикл 51) и `record_status.py` (цикл 50):
решение проверяется юнит-тестами без Postgres, Redis и FastAPI.
"""

# Роли, которым §18 даёт системный мониторинг целиком.
FULL_SYSTEM_METRICS_ROLES: tuple[str, ...] = ("admin",)

# Поля ответа, составляющие «системный мониторинг» по перечислению §9, за
# вычетом места на диске (см. шапку). Именно они скрываются от оператора.
HARDWARE_FIELDS: tuple[str, ...] = (
    "cpu_percent",
    "ram_percent",
    "ram_used_mb",
    "ram_total_mb",
    "temperature_c",
    "temperature_source",
)


def filter_system_metrics(metrics: dict, role: str) -> dict:
    """Готовит ответ `/api/system/metrics` к выдаче конкретной роли.

    Роли из :data:`FULL_SYSTEM_METRICS_ROLES` получают словарь **как есть**,
    без пересборки: админ-дашборд читает поля, которых здесь может быть не
    перечислено, и молчаливая потеря поля сломала бы его не сразу.

    Остальным (эндпоинт доступен только админу и оператору) поля железа
    удаляются целиком, а не заменяются на `None`: `null` фронтенд читает
    как «датчика нет» — то есть выдавал бы запрет за отсутствие железа, и
    оператор видел бы «температура недоступна» на сервере, где она есть.
    Ответ помечается флагом, чтобы страница могла сказать, почему раздела
    нет, вместо того чтобы молча его не рисовать.
    """
    if role in FULL_SYSTEM_METRICS_ROLES:
        return metrics
    limited = {k: v for k, v in metrics.items() if k not in HARDWARE_FIELDS}
    limited["system_metrics_limited"] = True
    return limited
