"""Единая кодировка CSV-выгрузок системы (SPEC §3, §8, §10).

**Зачем отдельный модуль ради одной строки.** Выгрузок в CSV три, и они
живут в разных местах: отчёты §8 (`services/reports.py`), журнал аудита
§10 (`routers/audit.py`) и конфигурация камер §3 (`routers/cameras.py`).
До этого модуля каждая кодировала результат сама — и к 64-му циклу они
разошлись: выгрузка камер писала BOM, две другие нет. Расхождение никем
не замечалось, потому что у CSV нет ошибки «неверная кодировка»: файл
открывается всегда, просто кириллица в нём выглядит как «Ð’Ñ€ÐµÐ¼Ñ».

**Почему BOM обязателен.** У .csv нет заголовка Content-Type, из которого
Excel мог бы узнать кодировку: открывая файл с диска, Excel под Windows
считает его записанным в ANSI-кодировке системы (для русской локали —
cp1251), пока не увидит BOM. То есть заголовки отчётов («Время»,
«Камера», «Персона» — все до одного кириллические) и любое русское имя
персоны или камеры превращались в мусор у того самого пользователя,
которому §8 обещает «экспорт в Excel/CSV». BOM — единственный признак,
по которому Excel переключается на UTF-8.

**Почему разделитель остаётся запятой.** У Excel под русской локалью
разделитель списка — точка с запятой, и CSV с запятыми он раскладывает в
один столбец. Соблазн поменять разделитель здесь же не реализован
намеренно: выгрузка камер §3 — не только отчёт, но и **вход импорта**
(`camera_config.parse_file`, круговой обход «выгрузил → поправил →
загрузил»), а RFC 4180 знает только запятую. Смена разделителя — вопрос
отдельной правки со своим круговым тестом; BOM же чинит кодировку, ничего
не ломая: `csv.reader` и `parse_file` (декодирует `utf-8-sig`) читают
файл с BOM так же, как без него.
"""

BOM = "﻿"


def encode(text: str) -> bytes:
    """Текст CSV → байты UTF-8 с BOM.

    Идемпотентно: повторный вызов на уже помеченном тексте не добавляет
    второй BOM. Это не теория — выгрузка камер помечала результат сама, и
    без защиты переход на общий вызов дал бы «\\ufeff\\ufeffname,...»,
    где первый столбец заголовка перестал бы совпадать с ожидаемым именем
    поля при импорте.
    """
    if text.startswith(BOM):
        text = text[len(BOM):]
    return (BOM + text).encode("utf-8")
