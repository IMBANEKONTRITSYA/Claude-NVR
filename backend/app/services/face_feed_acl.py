"""Фильтр живой ленты распознавания по роли (SPEC §18, §4, §15).

Канал `/ws/faces` обслуживает **две разные строки матрицы прав** сразу, и в
этом вся сложность:

* «Просмотр видео онлайн» (Да/Да/**Да**) — живая сетка рисует поверх видео
  рамки лиц с подписями, как того требует §4. Наблюдателю это разрешено.
* «Карточки персон» (Да/Да/**Нет**) — Стена распознавания показывает
  хранимый кадр лица, watchlist-разметку и историю событий. Наблюдателю это
  запрещено.

Оба потребителя (`LiveGrid.tsx` и `Wall.tsx`) слушают один и тот же сокет,
поэтому закрыть его наблюдателю целиком нельзя — это отняло бы у него §4,
— а оставить открытым значит отдать ему карточку персоны в реальном
времени. Отсюда фильтрация полей, а не доступа.

Модуль намеренно на голой стандартной библиотеке и вынесен из `ws.py`:
решение проверяется юнит-тестами без Postgres, Redis и FastAPI. Тот же
приём и по той же причине применён в `record_status.py` (цикл 50) — набор,
живущий внутри тяжёлого модуля, уходит в skip в лёгкой джобе CI, и код
оказывается проверенным только в песочнице.
"""
import json

# Роли, которым матрица прав §18 разрешает «Карточки персон», — то есть
# полную ленту Стены со снимками и watchlist-разметкой.
FACE_CARD_ROLES: tuple[str, ...] = ("admin", "operator")

# Поля, которые живому оверлею §4 нужны и которые карточкой персоны не
# являются: геометрия рамки, кадр-источник и подпись. `name` здесь
# осознанно: §4 требует рамки «с подписями», а §18 даёт наблюдателю
# строку «Просмотр видео онлайн» целиком. Секрет не имя человека перед
# камерой прямо сейчас, а его досье — снимки, теги, история.
_OVERLAY_FIELDS: tuple[str, ...] = (
    "type", "camera_id", "name", "is_known", "bbox", "frame_w", "frame_h",
)


def filter_face_message(raw: str, role: str) -> str | None:
    """Готовит сообщение ленты к отправке конкретной роли.

    Возвращает JSON-строку для отправки или ``None``, если сообщение этой
    роли не предназначено вовсе.

    Роли из :data:`FACE_CARD_ROLES` получают сообщение **байт в байт** —
    никакой пересборки: Стена и карточки читают поля, которых здесь может
    не быть перечислено, и молчаливая потеря поля сломала бы их не сразу,
    а на глазах у оператора.

    Наблюдатель получает только оверлейные поля. Сообщения, у которых
    оверлейной части нет вовсе (`enhanced` — обновление уже сохранённого
    снимка на Стене), ему не отправляются.
    """
    if role in FACE_CARD_ROLES:
        return raw

    try:
        data = json.loads(raw)
    except (ValueError, TypeError):
        # Нераспознанное сообщение наблюдателю не пересылается: неизвестный
        # формат нельзя отфильтровать, а пропустить его целиком значит
        # отдать неизвестно что.
        return None
    if not isinstance(data, dict):
        return None

    kind = data.get("type")
    if kind not in ("face", "box"):
        # `enhanced` и всё будущее, чей состав здесь не разобран, — мимо
        # наблюдателя. Умолчание закрытое: новое поле в ленте не должно
        # автоматически становиться видимым роли, которой карточки закрыты.
        return None

    # Рамку без геометрии рисовать нечем — такое сообщение наблюдателю
    # бесполезно, а значит и незачем.
    if not data.get("bbox") or not data.get("frame_w"):
        return None

    return json.dumps({k: data[k] for k in _OVERLAY_FIELDS if k in data})
