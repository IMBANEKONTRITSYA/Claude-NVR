"""Теги персон (SPEC §15: «Заметки, теги, watchlist»).

Один модуль на всю систему потому же, почему бэкап цикла 48 получил одну
реализацию на кнопку и на таймер: нормализация, разошедшаяся между записью
и фильтром, ломается молча. Тег, сохранённый как «VIP», и фильтр,
ищущий «vip», дают пустой список — и оператор видит не ошибку, а
«персон с таким тегом нет».

Три решения, из которых следует всё остальное:

1. **Канонический вид — нижний регистр.** Оператор набирает тег руками, на
   объекте их набирают несколько человек, и «Подрядчик»/«подрядчик»/
   «ПОДРЯДЧИК» — это один тег, а не три. Приведение при записи (а не при
   чтении) оставляет фильтр индексируемым: `tags @> ARRAY['подрядчик']`
   ложится на GIN-индекс, тогда как `lower(unnest(tags))` — нет.
2. **Отказ вместо усечения.** Список длиннее предела или тег длиннее
   предела — это 400 с внятным текстом, а не тихо обрезанный хвост.
   Молчаливое усечение здесь — тот же класс дефекта, что и «галочка
   watchlist отскакивает обратно» (см. комментарий в Persons.tsx).
3. **Порядок детерминирован.** Результат отсортирован, поэтому равенство
   списков проверяемо в тестах, а чипы в интерфейсе не прыгают между
   перерисовками.

Пустые строки — не данные, а следствие ввода «a,,b»; они отбрасываются
молча, и это единственное молчаливое действие в модуле.
"""

MAX_TAG_LEN = 40
MAX_TAGS_PER_PERSON = 20


class TagError(ValueError):
    """Ввод, который нельзя нормализовать, не потеряв данные оператора."""


def normalize_tag(raw: str) -> str:
    """Один тег в каноническом виде; пустая строка, если тега нет.

    Внутренние пробелы схлопываются: «служба   охраны» и «служба охраны» —
    один тег, различие в наборе не должно плодить сущности.
    """
    if not isinstance(raw, str):
        raise TagError("Тег должен быть строкой")
    return " ".join(raw.split()).lower()


def normalize_tags(raw: list[str] | None) -> list[str]:
    """Список тегов персоны: канонизация, дедупликация, сортировка.

    Пустой список и `None` — одно и то же «тегов нет»: колонка объявлена
    NOT NULL DEFAULT '{}', и NULL в неё не попадает ни одним путём.
    """
    if raw is None:
        return []
    if not isinstance(raw, (list, tuple)):
        raise TagError("Теги передаются списком строк")

    seen: set[str] = set()
    out: list[str] = []
    for item in raw:
        tag = normalize_tag(item)
        if not tag:
            continue
        if len(tag) > MAX_TAG_LEN:
            raise TagError(
                f"Тег длиннее {MAX_TAG_LEN} символов: «{tag[:MAX_TAG_LEN]}…»"
            )
        if tag in seen:
            continue
        seen.add(tag)
        out.append(tag)

    if len(out) > MAX_TAGS_PER_PERSON:
        raise TagError(
            f"У персоны не может быть больше {MAX_TAGS_PER_PERSON} тегов, "
            f"передано {len(out)}"
        )
    return sorted(out)


def merge_tags(left: list[str] | None, right: list[str] | None) -> list[str]:
    """Объединение тегов при слиянии персон (§15 «ручное слияние»).

    Слияние кластеров не должно терять разметку: оператор проставил теги
    обеим карточкам до того, как понял, что это один человек. Предел на
    количество здесь **не** применяется — иначе слияние двух законных
    карточек упало бы 400 на действии, где отказываться уже поздно:
    источник к этому моменту переносить некуда.
    """
    seen: set[str] = set()
    out: list[str] = []
    for tag in list(left or []) + list(right or []):
        canon = normalize_tag(tag)
        if not canon or canon in seen:
            continue
        seen.add(canon)
        out.append(canon)
    return sorted(out)
