"""Шкала архива: что именно записано у камеры за окно времени (SPEC §5).

Зачем отдельно от `archive_query.py`. Тот отвечает на вопрос «покажи
последние N сегментов по фильтру» — это выдача таблицы. Здесь другой
вопрос, тот, который оператор промышленного NVR задаёт первым:
**в какие минуты суток у этой камеры вообще есть запись, и где дыры**.

Разница не косметическая. Запись §5 непрерывная, а сегмент — 5 минут
(`mediamtx.yml: recordSegmentDuration`), то есть сутки одной камеры — это
288 строк таблицы, и «есть ли запись в 03:40» по ним читается перебором.
Дыра же (обрыв RTSP, перезапуск слоя записи, ротация по retention) в
таблице вообще не видна: отсутствие строки нельзя заметить, его можно
только вычислить.

Модуль состоит из двух частей:

* запрос сегментов, **пересекающих** окно (не «начавшихся внутри»: сегмент,
  начавшийся в 02:58 и закончившийся в 03:03, содержит 03:00 — по фильтру
  `started_at >= from` он бы потерялся, и шкала показала бы дыру там, где
  запись есть);
* чистое склеивание сегментов в диапазоны покрытия — оно не ходит в БД и
  потому проверяется без неё.
"""
from __future__ import annotations

from dataclasses import dataclass
from datetime import datetime, timedelta

from sqlalchemy import select

from ..models import VideoSegment

# Окно шкалы — не больше суток. Шкала суток и есть то, что показывает NVR;
# больший запрос не нужен оператору, но обязывает сервер собрать выдачу на
# тысячи сегментов, а браузер — её отрисовать.
MAX_TIMELINE_HOURS = 24

# Потолок числа сегментов в одном ответе. Сутки при 5-минутных сегментах —
# 288 строк, при минутных — 1440; 2000 покрывает оба режима с запасом.
# Ответ, упёршийся в потолок, помечается `truncated`, а не молча обрезается:
# обрезанная шкала выглядит как «дальше записи нет», то есть врёт ровно про
# то, ради чего её и смотрят.
MAX_TIMELINE_SEGMENTS = 2000

# Допуск склейки: сегменты, между которыми меньше этого, считаются
# непрерывной записью. MediaMTX закрывает файл и открывает следующий не
# мгновенно, и на шкале это дало бы 288 «дыр» в сутки — то есть шкала
# показывала бы разрывы там, где запись не прерывалась. Пять секунд взяты
# по §19 «восстановление потока ≤ 5 секунд после обрыва»: всё, что дольше,
# уже является перерывом записи по мерке ТЗ, и прятать его нельзя.
JOIN_GAP_SEC = 5.0


@dataclass
class Coverage:
    """Непрерывный кусок записи на шкале."""
    start: datetime
    end: datetime

    @property
    def duration_sec(self) -> float:
        return (self.end - self.start).total_seconds()


def timeline_query(camera_id: int, date_from: datetime, date_to: datetime,
                   limit: int = MAX_TIMELINE_SEGMENTS):
    """Сегменты камеры, пересекающие окно, по возрастанию времени.

    Порядок здесь обратный выдаче таблицы (там — от свежих к старым):
    шкала и цепочка воспроизведения читаются слева направо, и разворот на
    стороне браузера означал бы, что при упоре в `limit` отбрасывается
    начало окна вместо конца.
    """
    return (
        select(VideoSegment)
        .where(
            VideoSegment.camera_id == camera_id,
            VideoSegment.started_at < date_to,
            VideoSegment.ended_at > date_from,
        )
        .order_by(VideoSegment.started_at)
        .limit(limit)
    )


def merge_coverage(segments, join_gap_sec: float = JOIN_GAP_SEC) -> list[Coverage]:
    """Склеивает сегменты в диапазоны покрытия.

    На вход — последовательность объектов с `started_at`/`ended_at`,
    отсортированная по началу (так отдаёт `timeline_query`). Пересечения и
    вложенность обрабатываются наравне с примыканием: слой записи может
    переоткрыть путь после обрыва и записать перекрывающийся хвост, и два
    диапазона поверх одного и того же времени на шкале — артефакт.
    """
    out: list[Coverage] = []
    gap = timedelta(seconds=join_gap_sec)
    for seg in segments:
        start, end = seg.started_at, seg.ended_at
        if end < start:
            # Битая строка индексации (конец раньше начала) не должна
            # растягивать диапазон назад: считаем её точкой.
            end = start
        if out and start - out[-1].end <= gap:
            if end > out[-1].end:
                out[-1].end = end
            continue
        out.append(Coverage(start=start, end=end))
    return out


def recorded_seconds(ranges: list[Coverage]) -> float:
    """Сколько секунд записи внутри окна. Считается по склеенным
    диапазонам, а не суммой `duration_sec` сегментов: перекрытие после
    переоткрытия пути дало бы «записано 25 часов из 24»."""
    return sum(r.duration_sec for r in ranges)


def clamp_ranges(ranges: list[Coverage], date_from: datetime,
                 date_to: datetime) -> list[Coverage]:
    """Обрезает диапазоны границами окна.

    Крайние сегменты выходят за окно по построению (`timeline_query`
    отбирает по пересечению), и без обрезки шкала суток получала бы
    полоску, вылезающую за свои края, а «записано за сутки» — больше суток.
    """
    out: list[Coverage] = []
    for r in ranges:
        start = max(r.start, date_from)
        end = min(r.end, date_to)
        if end > start:
            out.append(Coverage(start=start, end=end))
    return out
