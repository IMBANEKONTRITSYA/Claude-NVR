"""Пересчёт центроида персоны (SPEC §15).

**Что такое центроид и почему он обязан меняться вместе с карточкой.**
Распознавание сличает каждое новое лицо не с галереей снимков, а с
единственным вектором `persons.centroid` (`find_or_create_person` в
воркере: ближайший центроид по косинусу, и если расстояние меньше
«порога схожести» — это он). То есть центроид — не справочное поле
карточки, а то, ЧЕМ карточка узнаётся.

**Почему модуль появился.** Автоматическая DBSCAN-рекластеризация
(`worker.recluster_unknowns`) после слияния кластера всегда пересчитывала
центроид: берёт средний вектор по событиям кластера и нормирует его.
Ручное же слияние карточек (`POST /api/persons/{src}/merge/{dst}`, §15
«Ручное слияние кластеров») переносило события и теги и центроид цели не
трогало вовсе. Два пути слияния расходились — и расходились в ту сторону,
где хуже: ручной путь выполняет оператор, глазами убедившийся, что это
один человек.

Следствие измерено на живом стенде (цикл 65): появление, попадавшее в
слитую карточку, остаётся от центроида цели так же далеко, как было, —
и заводит ТРЕТЬЮ карточку. Оператор сливает её снова, и так без конца:
ручное слияние не учило систему ничему. С пересчитанным центроидом то же
появление попадает в объединённую карточку.

**Почему среднее считает Postgres, а нормирует Python.** `avg(embedding)`
по событиям персоны — одна строка на выходе вместо выгрузки всех
эмбеддингов (на объекте их у персоны могут быть тысячи: 512 float на
событие). А вот нормировать в SQL нечем: `l2_normalize` появился только
в pgvector 0.7, а ТЗ §21 требует «PostgreSQL 15+ с pgvector» без привязки
к версии — на 0.6 (той, что в песочнице) такой запрос упал бы. Норма же
в чистом Python — 512 умножений, и numpy для неё в зависимостях бэкенда
не нужен.

Приведение `::text` — не перестраховка: адаптер pgvector для asyncpg в
`db.py` не регистрируется (вектора пишутся и читаются сырым SQL по всему
бэкенду), и без приведения на выходе оказался бы объект, чей вид зависит
от драйвера.
"""
from __future__ import annotations

import math

from sqlalchemy import text
from sqlalchemy.ext.asyncio import AsyncSession


def parse_vector(raw: str | None) -> list[float] | None:
    """Текстовое представление pgvector («[1,2,3]») → список float."""
    if not raw:
        return None
    body = raw.strip()
    if body.startswith("[") and body.endswith("]"):
        body = body[1:-1]
    if not body.strip():
        return None
    return [float(x) for x in body.split(",")]


def normalize(vec: list[float]) -> list[float] | None:
    """Нормирует вектор к единичной длине. None — если норма нулевая.

    Нормировка обязательна, а не косметика: тот же шаг делает
    `recluster_unknowns`, а косинусное расстояние по ненормированному
    центроиду дало бы карточку, которая узнаётся «почти всем».
    """
    norm = math.sqrt(sum(x * x for x in vec))
    if norm <= 1e-9:
        return None
    return [x / norm for x in vec]


def format_vector(vec: list[float]) -> str:
    return "[" + ",".join(repr(float(x)) for x in vec) + "]"


async def recompute_centroid(db: AsyncSession, pid: int) -> bool:
    """Центроид персоны := нормированное среднее эмбеддингов её событий.

    Возвращает True, если центроид переписан. False означает «пересчитывать
    было нечем» — у персоны нет ни одного события с эмбеддингом, и тогда
    прежний центроид сохраняется: он всё ещё лучше, чем NULL (карточка с
    NULL не участвует в распознавании вовсе).

    Коммит — за вызывающей стороной: в слиянии этот UPDATE обязан попасть
    в ту же транзакцию, что перенос событий, иначе между ними существует
    момент, когда события уже у цели, а узнаётся она по старому вектору.
    """
    raw = (await db.execute(text(
        "SELECT avg(embedding)::text FROM face_events "
        "WHERE person_id = :p AND embedding IS NOT NULL"
    ), {"p": pid})).scalar()
    vec = parse_vector(raw)
    if vec is None:
        return False
    unit = normalize(vec)
    if unit is None:
        return False
    await db.execute(text(
        "UPDATE persons SET centroid = CAST(:c AS vector) WHERE id = :p"
    ), {"c": format_vector(unit), "p": pid})
    return True
