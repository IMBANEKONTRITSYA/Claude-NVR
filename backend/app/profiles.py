"""Профили производительности аналитики (SPEC §15).

Профиль задаёт связный набор параметров обработки. Любой параметр можно
переопределить вручную — профиль лишь заполняет значения по умолчанию.
Воркер читает итоговые значения из таблицы settings.

**Профиль применяется только к слою аналитики** (SPEC §15: «Профиль
применяется ТОЛЬКО к слою аналитики, запись не затрагивается»). Ни один
ключ ниже не влияет на запись: камеры пишутся MediaMTX без декодирования
независимо от выбранного профиля, и смена профиля не может уронить или
замедлить запись — это прямое требование §2 о независимости слоёв.

Масштаб, к которому относятся профили, — это число камер **в режиме
analytics** (§1: «от 0 до N, конфигурируется, зависит от возможностей
сервера»), а не число камер записи, которое на порядок больше. По §20
GPU становится «опциональным» после 10 камер аналитики и
«рекомендуемым» после 20; на сервере без GPU выше этих чисел упор идёт
в CPU, и сколько именно каналов проходит — считает калькулятор §16
(`services/autoconfig.py`), а не константа здесь.

Числа в самих профилях подобраны как связные наборы «дешевле/дороже», а
не выведены из замера на целевом железе: инференс на CPU без AVX2 в
песочнице не воспроизводится. Пересчёт под фактические ms/лицо — пункт
чек-листа первого развёртывания, см. docs/DEPLOY_CHECKLIST.md.
"""

PROFILES: dict[str, dict] = {
    # Наименьшая нагрузка на ядро: детектор только по движению, каждый 4-й
    # кадр, лёгкая модель, апскейл лишь по требованию оператора.
    "economy": {
        "detection_fps": 5,
        "frame_skip": 3,          # анализировать каждый 4-й кадр
        "motion_prefilter": 1,    # детектор лиц только по движению
        "idle_fps": 1,            # частота при длительном отсутствии движения
        "face_model": "buffalo_s",
        "upscale_mode": "manual",  # апскейл только по запросу оператора
        "cluster_interval_min": 60,
        "detect_width": 640,
    },
    # Режим по умолчанию: тот же префильтр движения и та же лёгкая модель,
    # но анализируется каждый кадр из отобранных и в фоне улучшается аватар.
    "standard": {
        "detection_fps": 10,
        "frame_skip": 1,
        "motion_prefilter": 1,
        "idle_fps": 2,
        "face_model": "buffalo_s",
        "upscale_mode": "avatar",  # в фоне улучшается только аватар персоны
        "cluster_interval_min": 15,
        "detect_width": 640,
    },
    # Максимальное качество ценой CPU: префильтр выключен (детектор идёт по
    # КАЖДОМУ кадру), тяжёлая модель buffalo_l, кадр 960 px вместо 640.
    # Самый дорогой режим из трёх: по §16 канал аналитики стоит 0.5–1.5
    # ядра на лёгкой модели, здесь — заметно больше по сумме множителей,
    # а §19 оставляет машине запас («CPU ≤ 80 % при полной нагрузке»).
    "maximum": {
        "detection_fps": 15,
        "frame_skip": 0,
        "motion_prefilter": 0,     # анализируется каждый кадр
        "idle_fps": 5,
        "face_model": "buffalo_l",
        "upscale_mode": "all",     # апскейл всей галереи в фоне
        "cluster_interval_min": 5,
        "detect_width": 960,
    },
}

DEFAULT_PROFILE = "standard"

# Ключи, которыми управляет профиль (их значения перезаписываются при его смене)
PROFILE_KEYS = tuple(PROFILES[DEFAULT_PROFILE].keys())


def profile_settings(name: str) -> dict[str, str]:
    """Значения профиля в виде строк для таблицы settings."""
    data = PROFILES.get(name) or PROFILES[DEFAULT_PROFILE]
    return {k: str(v) for k, v in data.items()}
